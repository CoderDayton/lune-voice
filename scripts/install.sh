#!/usr/bin/env bash
set -euo pipefail

BINARY="lune-voice"
PACKAGE="lune-app"

# ── Colors ────────────────────────────────────────────────────────────────────
red()   { printf '\033[31m%s\033[0m\n' "$*"; }
green() { printf '\033[32m%s\033[0m\n' "$*"; }
bold()  { printf '\033[1m%s\033[0m\n' "$*"; }
info()  { printf '  %s\n' "$*"; }

bold "==> lune-voice install"

# ── Step 1: Shut down running daemon ─────────────────────────────────────────
if command -v "$BINARY" &>/dev/null; then
    info "Found existing binary at $(command -v "$BINARY")"

    if "$BINARY" status &>/dev/null 2>&1; then
        info "Daemon is running — sending quit..."
        "$BINARY" quit || true
        # Give it a moment to exit cleanly.
        sleep 1
        # Verify it stopped.
        if "$BINARY" status &>/dev/null 2>&1; then
            red "Daemon did not stop; killing by D-Bus name..."
            # Last resort: kill the process holding the bus name.
            if command -v busctl &>/dev/null; then
                pid=$(busctl status com.lunevoice.Daemon1 2>/dev/null \
                    | awk '/^PID:/ { print $2 }') || true
                if [[ -n "${pid:-}" ]]; then
                    info "Killing PID $pid"
                    kill "$pid" || true
                    sleep 1
                fi
            fi
        else
            green "Daemon stopped."
        fi
    else
        info "Daemon not running."
    fi

    # ── Step 2: Remove old binary ─────────────────────────────────────────────
    info "Removing old binary..."
    cargo uninstall "$BINARY" 2>/dev/null || rm -f "$(command -v "$BINARY")"
    green "Old binary removed."
else
    info "No existing installation found."
fi

# ── Step 3: Detect CUDA ───────────────────────────────────────────────────────
FEATURES=""
if command -v nvidia-smi &>/dev/null && nvidia-smi &>/dev/null; then
    info "NVIDIA GPU detected — enabling CUDA"
    FEATURES="--features cuda"
else
    info "No NVIDIA GPU detected — CPU only"
fi

# ── Step 3b: Ensure clipboard tools ───────────────────────────────────────────
MISSING=()
for tool in wl-copy wl-paste xdotool; do
    if ! command -v "$tool" &>/dev/null; then
        MISSING+=("$tool")
    fi
done
if [[ ${#MISSING[@]} -gt 0 ]]; then
    info "Installing missing tools: ${MISSING[*]}"
    sudo apt install -y wl-clipboard xdotool 2>/dev/null || \
        info "Could not auto-install. Please install: ${MISSING[*]}"
fi

# ── Step 4: Build release ─────────────────────────────────────────────────────
bold "==> Building release..."
cargo build --release -p "$PACKAGE" $FEATURES
green "Build complete."

# ── Step 5: Install ──────────────────────────────────────────────────────────
bold "==> Installing..."
cargo install --path "crates/$PACKAGE" --force $FEATURES
green "Installed $(command -v "$BINARY")"

# ── Step 6: Ensure ORT CUDA shared libs are discoverable ─────────────────────
# ORT loads CUDA provider via dlopen — needs LD_LIBRARY_PATH to find the .so files.
# The ort crate downloads them to ~/.cache/ort.pyke.io/dfbin/ at build time.
ORT_CACHE="$HOME/.cache/ort.pyke.io/dfbin"
if [[ -n "$FEATURES" && -d "$ORT_CACHE" ]]; then
    ORT_LIB_DIR=$(find "$ORT_CACHE" -name 'libonnxruntime_providers_cuda.so' -printf '%h\n' 2>/dev/null | head -1)
    if [[ -n "$ORT_LIB_DIR" ]]; then
        # Write a shell profile snippet so LD_LIBRARY_PATH is set on login.
        PROFILE_SNIPPET="$HOME/.config/lune-voice/ort-env.sh"
        mkdir -p "$(dirname "$PROFILE_SNIPPET")"
        cat > "$PROFILE_SNIPPET" <<ENVEOF
# Auto-generated by lune-voice install — ORT CUDA provider shared libs
export LD_LIBRARY_PATH="${ORT_LIB_DIR}\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
ENVEOF
        # Source it in .profile / .bashrc / .zshrc if not already present
        for rc in "$HOME/.zshrc" "$HOME/.bashrc"; do
            if [[ -f "$rc" ]] && ! grep -q 'ort-env.sh' "$rc" 2>/dev/null; then
                printf '\n# lune-voice ORT CUDA libs\n[ -f "%s" ] && source "%s"\n' \
                    "$PROFILE_SNIPPET" "$PROFILE_SNIPPET" >> "$rc"
                info "Added ORT env to $(basename "$rc")"
            fi
        done
        # Also export for current session
        export LD_LIBRARY_PATH="${ORT_LIB_DIR}${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
        green "ORT CUDA libs at $ORT_LIB_DIR"
        info "Restart your shell or run: source $PROFILE_SNIPPET"
    else
        info "ORT CUDA libs not found in cache — CUDA EP may not work."
    fi
else
    info "No CUDA features or ORT cache — skipping CUDA lib setup."
fi

# ── Step 7: Link models ─────────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
PROJECT_MODELS="$PROJECT_ROOT/models"
XDG_DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
APP_MODELS="$XDG_DATA/lune-voice/models"

if [[ -d "$PROJECT_MODELS" ]]; then
    mkdir -p "$XDG_DATA/lune-voice"
    if [[ -L "$APP_MODELS" ]]; then
        # Already a symlink — update if pointing elsewhere
        current="$(readlink -f "$APP_MODELS")"
        if [[ "$current" != "$(readlink -f "$PROJECT_MODELS")" ]]; then
            info "Updating models symlink..."
            ln -sfn "$PROJECT_MODELS" "$APP_MODELS"
        else
            info "Models symlink already correct."
        fi
    elif [[ -d "$APP_MODELS" ]]; then
        info "Models directory exists at $APP_MODELS (not a symlink — skipping)"
        info "To use project models: rm -rf '$APP_MODELS' && ln -s '$PROJECT_MODELS' '$APP_MODELS'"
    else
        info "Linking models: $APP_MODELS -> $PROJECT_MODELS"
        ln -s "$PROJECT_MODELS" "$APP_MODELS"
    fi
    green "Models ready."
else
    info "No models/ directory in project root — skipping model link."
    info "Models will be downloaded on first run."
fi

bold "==> Done. Run: $BINARY daemon"
