# Write THIRD_PARTY_LICENSES.md: the licence texts of every Rust crate compiled
# into the release binary (cargo-about, configured by about.toml) and every
# JavaScript package in the interface bundle
# (desktop-ui/scripts/third-party-licenses.ts). The hand-written notices for
# native libraries, fonts, data files and the vendored fork stay in
# THIRD_PARTY_NOTICES.md. Both files ship inside every bundle.
#
#   bash scripts/release/third-party-licenses.sh          # rewrite the file
#   bash scripts/release/third-party-licenses.sh --check  # fail if it is stale
#
# Needs cargo-about 0.9.2, the version release.yml pins (`cargo install
# cargo-about --locked --features cli --version 0.9.2`), bun,
# and the frontend dependencies installed (`bun install` in desktop-ui/).
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$REPO_ROOT/THIRD_PARTY_LICENSES.md"
MODE="${1:-}"

if ! command -v cargo-about >/dev/null; then
    echo "cargo-about is not installed: cargo install cargo-about --locked --features cli --version 0.9.2" >&2
    exit 1
fi
if [ ! -d "$REPO_ROOT/desktop-ui/node_modules" ]; then
    echo "frontend dependencies are missing: run bun install in desktop-ui/" >&2
    exit 1
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
    printf '# Third-Party Licenses\n\n'
    printf 'Generated by `scripts/release/third-party-licenses.sh`. Do not edit by hand.\n\n'
    printf 'The licence texts of the open-source Rust crates and JavaScript packages\n'
    printf 'built into Lune Voice. Native libraries, fonts, data files and models are\n'
    printf 'covered in THIRD_PARTY_NOTICES.md.\n\n'
    # `--fail` stops on any crate whose licence cannot be determined, so a new
    # dependency cannot drop out of the file silently. `whisper-cpp` is the
    # feature every release build enables.
    cargo about generate --fail \
        --manifest-path "$REPO_ROOT/desktop-ui/src-tauri/Cargo.toml" \
        --features whisper-cpp \
        -c "$REPO_ROOT/about.toml" \
        "$REPO_ROOT/scripts/release/about.hbs"
    printf '\n'
    bun "$REPO_ROOT/desktop-ui/scripts/third-party-licenses.ts"
} > "$tmp"

if [ "$MODE" = "--check" ]; then
    if ! cmp -s "$tmp" "$OUT"; then
        echo "THIRD_PARTY_LICENSES.md is out of date: run bash scripts/release/third-party-licenses.sh" >&2
        exit 1
    fi
    echo "THIRD_PARTY_LICENSES.md is current"
else
    cat "$tmp" > "$OUT"
    echo "wrote $OUT"
fi
