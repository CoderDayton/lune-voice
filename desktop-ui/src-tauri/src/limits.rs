//! The one definition of every input limit the backend enforces.
//!
//! These used to be written twice — a Rust constant on the command side and a
//! hand-copied `maxLength` in the form — and they had already drifted: the
//! backend counts **UTF-8 bytes** and the DOM counts UTF-16 code units, so a
//! name of 64 emoji passed the form and was rejected by the command that
//! received it.
//!
//! So the values live here and the TypeScript half is generated from them
//! ([`typescript_module`], written by the test at the bottom of this file into
//! `desktop-ui/src/lib/backend/generated/limits.ts`). CI's DTO-drift job
//! regenerates that directory and fails on any diff, which is what keeps the
//! two halves honest.
//!
//! Lengths are **bytes**, because that is what `str::len` — the thing actually
//! doing the rejecting — measures.

/// Dictionary phrase and replacement.
pub const DICT_ENTRY_MAX_BYTES: usize = 1024;

/// Snippet trigger phrase.
pub const SNIPPET_TRIGGER_MAX_BYTES: usize = 256;

/// Snippet body template.
pub const SNIPPET_BODY_MAX_BYTES: usize = 16_384;

/// Custom style name.
pub const STYLE_NAME_MAX_BYTES: usize = 64;

/// Custom style description.
pub const STYLE_DESC_MAX_BYTES: usize = 256;

/// Custom style instructions.
pub const STYLE_INSTRUCTIONS_MAX_BYTES: usize = 2048;

/// Distance from the screen edge to the pill, in logical pixels.
pub const PILL_EDGE_MARGIN_MAX: u32 = 512;

/// Confidence threshold, inclusive. The settings slider deliberately offers a
/// narrower range than this — the extremes are technically valid and
/// practically useless — but it can never offer more.
pub const CONFIDENCE_MIN: f32 = 0.0;
pub const CONFIDENCE_MAX: f32 = 1.0;

// Checked at compile time: a limit pair the wrong way round would reject every
// value rather than fail visibly.
const _: () = assert!(HISTORY_DAYS_MIN < HISTORY_DAYS_MAX);

/// History retention window, in days, when retention is enabled at all.
pub const HISTORY_DAYS_MIN: u32 = 1;
pub const HISTORY_DAYS_MAX: u32 = 3650;

/// The "keep forever" sentinel for the retention window. Zero is free to mean
/// this because a zero-day window would delete every session the moment it was
/// written — see `UserSettings::history_retention`.
pub const HISTORY_DAYS_FOREVER: u32 = 0;

/// Session ids accepted by one `delete_sessions` call.
///
/// The History tab selects across pages, so the list is user-controlled; the
/// cap keeps a runaway selection from building an unbounded SQL `IN (…)`.
pub const HISTORY_BULK_DELETE_MAX: usize = 1000;

/// Render the generated TypeScript module.
#[cfg(test)]
fn typescript_module() -> String {
    format!(
        "// This file is generated from `desktop-ui/src-tauri/src/limits.rs`. Do not edit this file manually.\n\
         //\n\
         // Lengths are UTF-8 **byte** counts, matching what the backend measures.\n\
         // Use `byteLength()` to compare against them — `String.length` counts\n\
         // UTF-16 code units and disagrees on anything outside ASCII.\n\
         \n\
         export const LIMITS = {{\n\
         \x20 dictEntryMaxBytes: {DICT_ENTRY_MAX_BYTES},\n\
         \x20 snippetTriggerMaxBytes: {SNIPPET_TRIGGER_MAX_BYTES},\n\
         \x20 snippetBodyMaxBytes: {SNIPPET_BODY_MAX_BYTES},\n\
         \x20 styleNameMaxBytes: {STYLE_NAME_MAX_BYTES},\n\
         \x20 styleDescMaxBytes: {STYLE_DESC_MAX_BYTES},\n\
         \x20 styleInstructionsMaxBytes: {STYLE_INSTRUCTIONS_MAX_BYTES},\n\
         \x20 pillEdgeMarginMax: {PILL_EDGE_MARGIN_MAX},\n\
         \x20 confidenceMin: {CONFIDENCE_MIN:?},\n\
         \x20 confidenceMax: {CONFIDENCE_MAX:?},\n\
         \x20 historyDaysMin: {HISTORY_DAYS_MIN},\n\
         \x20 historyDaysMax: {HISTORY_DAYS_MAX},\n\
         \x20 historyDaysForever: {HISTORY_DAYS_FOREVER},\n\
         \x20 historyBulkDeleteMax: {HISTORY_BULK_DELETE_MAX},\n\
         }} as const;\n\
         \n\
         /** UTF-8 byte length of `value`, the unit every `*MaxBytes` limit is in. */\n\
         export function byteLength(value: string): number {{\n\
         \x20 return new TextEncoder().encode(value).length;\n\
         }}\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Regenerates the TypeScript half. Mirrors how the ts-rs DTO bindings are
    /// emitted, so `cargo test -p lune-ui` refreshes everything under
    /// `generated/` and CI's drift job catches a limit changed on only one side.
    #[test]
    fn export_bindings_limits() {
        let path = std::path::Path::new("../src/lib/backend/generated/limits.ts");
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).expect("create generated dir");
        }
        std::fs::write(path, typescript_module()).expect("write limits.ts");
    }

    /// The generated module has to actually carry the values, not just compile.
    /// A formatting slip here would ship a TypeScript file the build rejects.
    #[test]
    fn the_generated_module_carries_the_rust_values() {
        let ts = typescript_module();
        assert!(ts.contains(&format!("styleNameMaxBytes: {STYLE_NAME_MAX_BYTES},")));
        assert!(ts.contains(&format!("pillEdgeMarginMax: {PILL_EDGE_MARGIN_MAX},")));
        assert!(ts.contains("export function byteLength"));
    }
}
